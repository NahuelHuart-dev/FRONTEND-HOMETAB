const savedLocale = localStorage.getItem('hometab_locale')
const browserLocale = navigator.language?.slice(0, 2)
const initialLocale = SUPPORTED_LOCALES.some((locale) => locale.code === savedLocale)
  ? savedLocale
  : SUPPORTED_LOCALES.some((locale) => locale.code === browserLocale)
    ? browserLocale
    : fallbackLocale

export const i18n = createI18n({
  legacy: false,
  locale: initialLocale,
  fallbackLocale,
  messages,
})

export const setLocale = (locale) => {
  if (!SUPPORTED_LOCALES.some((item) => item.code === locale)) return
  i18n.global.locale.value = locale
  localStorage.setItem('hometab_locale', locale)
  document.documentElement.lang = locale
}

document.documentElement.lang = initialLocale
